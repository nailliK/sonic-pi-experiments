#!/usr/bin/env ruby
# spi:ignore
# Generates a Ruby stub file describing Sonic Pi's language, so that
# JetBrains IDEs (or any Ruby-aware editor) can offer completion and quick
# documentation for play, live_loop, sample, and friends.
#
# Sonic Pi defines these methods dynamically at runtime, which is why an IDE
# can't see them. Happily, every function carries full metadata (args, opts,
# docs, examples) in its internal doc system, so we can load the language
# modules without booting a server and emit real method definitions from it.
#
# Usage:
#   ruby gen-stubs.rb [OUTPUT_FILE]
#
# Default output: ./stubs/sonic_pi.rb

require "fileutils"

APP = ENV.fetch("SONIC_PI_APP", "/Applications/Sonic Pi.app")
RUBY_SERVER = File.join(APP, "Contents/Resources/app/server/ruby")

unless File.directory?(RUBY_SERVER)
  abort "Could not find Sonic Pi at #{APP}\n" \
        "Set SONIC_PI_APP to your install location."
end

$LOAD_PATH << File.join(RUBY_SERVER, "lib")
require File.join(RUBY_SERVER, "core.rb")

Dir[File.join(RUBY_SERVER, "lib/sonicpi/lang/*.rb")].sort.each do |f|
  begin
    require f
  rescue Exception => e
    warn "note: skipped #{File.basename(f)} (#{e.class})"
  end
end

DOCS = SonicPi::Lang::Core.docs
abort "No documentation found - has Sonic Pi's internal layout changed?" if DOCS.empty?

# --- helpers -----------------------------------------------------------

RESERVED = %w[
  BEGIN END alias and begin break case class def defined? do else elsif end
  ensure false for if in module next nil not or redo rescue retry return self
  super then true undef unless until when while yield
].freeze

def safe_param(name)
  n = name.to_s
  RESERVED.include?(n) ? "_#{n}" : n
end

def wrap(text, width = 96)
  return [] if text.nil? || text.to_s.strip.empty?
  text.to_s.split("\n").flat_map do |para|
    para.strip.empty? ? [""] : para.scan(/\S.{0,#{width - 1}}(?:\s|$)/).map(&:strip)
  end
end

def type_of(sym)
  sym.to_s.split("_or_").map { |t| t.split("_").map(&:capitalize).join }.join(", ")
end

# --- generate ----------------------------------------------------------

out = []
out << "# frozen_string_literal: true"
out << "# spi:ignore"
out << "#"
out << "# Sonic Pi language stubs - FOR EDITOR COMPLETION ONLY."
out << "#"
out << "# Generated by gen-stubs.rb from Sonic Pi's own documentation metadata."
out << "# Do not run this file in Sonic Pi: these are empty definitions and would"
out << "# shadow the real ones. The `# spi:ignore` marker above keeps `spi watch`"
out << "# from doing so by accident."
out << "#"
out << "# Regenerate after upgrading Sonic Pi:  ruby gen-stubs.rb"
out << "#"
out << "# Sonic Pi #{SonicPi::VERSION rescue '5'} - #{DOCS.size} functions"
out << ""

DOCS.keys.sort.each do |name|
  info = DOCS[name]
  args = info[:args] || []
  opts = info[:opts] || {}
  opts = {} unless opts.is_a?(Hash)

  out << "#"
  wrap(info[:summary]).each { |l| out << "# #{l}".rstrip }
  out << "#"
  wrap(info[:doc]).each { |l| out << "# #{l}".rstrip }

  if (usage = info[:usage_example])
    out << "#"
    out << "# @example"
    wrap(usage, 88).each { |l| out << "#   #{l}".rstrip }
  end

  Array(info[:examples]).first(2).each do |ex|
    out << "#"
    out << "# @example"
    ex.to_s.split("\n").first(14).each { |l| out << "#   #{l}".rstrip }
  end

  out << "#"
  args.each do |arg_name, arg_type|
    out << "# @param #{safe_param(arg_name)} [#{type_of(arg_type)}]"
  end

  opts.each do |opt_name, desc|
    summary = wrap(desc, 78).first
    out << "# @option opts [Object] :#{opt_name} #{summary}".rstrip
  end

  out << "# @return [#{info[:returns] ? type_of(info[:returns]) : 'Object'}]"
  out << "# @since #{info[:introduced]}" if info[:introduced]

  # Some functions (mostly MIDI) document a name as both a positional arg and
  # an opt. Ruby won't accept the duplicate, so first declaration wins.
  seen = {}
  params = []
  args.each do |arg_name, _|
    p = safe_param(arg_name)
    next if seen[p]
    seen[p] = true
    params << "#{p} = nil"
  end
  opts.each_key do |opt_name|
    p = safe_param(opt_name)
    next if seen[p]
    seen[p] = true
    params << "#{p}: nil"
  end
  params << "&blk" if info[:accepts_block]

  signature = params.empty? ? "" : "(#{params.join(', ')})"
  out << "def #{name}#{signature}; end"
  out << ""
end

# Reference lists: names you pass as symbols, which completion can't infer.
def reference_list(out, title, values)
  return if values.nil? || values.empty?
  out << "# #{title} (#{values.size}):"
  values.map(&:to_s).sort.each_slice(6) do |row|
    out << "#   #{row.join(', ')}"
  end
  out << "#"
end

out << "# " + "-" * 70
out << "# Reference: names to pass as symbols, e.g. play with synth: :prophet"
out << "# " + "-" * 70
out << "#"

begin
  si = SonicPi::Synths::SynthInfo
  reference_list(out, "Synths", si.all_synths) if si.respond_to?(:all_synths)
  reference_list(out, "FX", si.all_fx) if si.respond_to?(:all_fx)
  reference_list(out, "Samples", si.all_samples) if si.respond_to?(:all_samples)
rescue Exception => e
  warn "note: could not list synths/fx/samples (#{e.class})"
end

begin
  reference_list(out, "Scales", SonicPi::Scale::SCALE.keys)
  reference_list(out, "Chords", SonicPi::Chord::CHORD.keys)
rescue Exception => e
  warn "note: could not list scales/chords (#{e.class})"
end

target = ARGV[0] || File.join(Dir.pwd, "stubs", "sonic_pi.rb")
FileUtils.mkdir_p(File.dirname(target))
File.write(target, out.join("\n") + "\n")

puts "Wrote #{target}"
puts "  #{DOCS.size} functions, #{out.size} lines"
